import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const generatedDir = path.join(rootDir, 'src', 'device', 'proto', 'generated')
const marker = 'AUTO-GENERATED by npm run proto:gen from webhmi.proto. Do not edit by hand.'

async function markFile(relativePath) {
  const filePath = path.join(generatedDir, relativePath)
  const text = await readFile(filePath, 'utf8')
  if (text.includes(marker)) return

  if (relativePath.endsWith('.js') && text.startsWith('/*eslint-disable')) {
    const firstNewline = text.indexOf('\n')
    const head = text.slice(0, firstNewline + 1)
    const rest = text.slice(firstNewline + 1)
    await writeFile(filePath, `${head}// ${marker}\n${rest}`)
    return
  }

  await writeFile(filePath, `// ${marker}\n${text}`)
}

await Promise.all([
  markFile('webhmi.js'),
  markFile('webhmi.d.ts'),
  writeFile(
    path.join(generatedDir, 'README.md'),
    'This folder is generated by `npm run proto:gen` from `webhmi.proto`.\n\nDo not edit files here by hand.\n',
  ),
])

console.log('Marked generated protobuf files.')
