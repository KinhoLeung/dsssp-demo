import fs from 'node:fs/promises'
import path from 'node:path'
import protobuf from 'protobufjs'

const REPO_ROOT = process.cwd()
const PROTO_PATH = path.join(REPO_ROOT, 'webhmi.proto')
const JSON_PATH = path.join(REPO_ROOT, 'deviceDB.json')

const OUTPUTS = [
  path.join(REPO_ROOT, 'gatt_server_service_table', 'main', 'webhmi_getdb_payload.h'),
  path.join(REPO_ROOT, 'tusb_hid', 'main', 'webhmi_getdb_payload.h'),
]

const toCByteArray = (bytes) => {
  const cols = 12
  const hexes = Array.from(bytes, (b) => `0x${b.toString(16).padStart(2, '0')}`)
  const lines = []
  for (let i = 0; i < hexes.length; i += cols) lines.push(`  ${hexes.slice(i, i + cols).join(', ')}`)
  return lines.join(',\n')
}

const main = async () => {
  await fs.stat(PROTO_PATH)
  await fs.stat(JSON_PATH)

  const root = await protobuf.load(PROTO_PATH)
  const type = root.lookupType('webhmi.GetDbResponse')

  const jsonText = await fs.readFile(JSON_PATH, 'utf8')
  const json = JSON.parse(jsonText)

  const message = type.fromObject(json)
  const bytes = type.encode(message).finish()

  const header = `#pragma once

// Auto-generated by \`node scripts/gen-firmware-getdb.mjs\`
// Source: deviceDB.json -> webhmi.GetDbResponse protobuf payload (NOT framed).
// NOTE: Firmware will still wrap this payload in protocol.md framing at runtime.

#include <stddef.h>
#include <stdint.h>

static const uint8_t WEBHMI_GETDB_RESPONSE_PB[] = {
${toCByteArray(bytes)}
};

static const size_t WEBHMI_GETDB_RESPONSE_PB_LEN = sizeof(WEBHMI_GETDB_RESPONSE_PB);
`

  await Promise.all(
    OUTPUTS.map(async (outPath) => {
      await fs.mkdir(path.dirname(outPath), { recursive: true })
      await fs.writeFile(outPath, header, 'utf8')
    }),
  )

  console.log(`Generated GetDbResponse payload: ${bytes.length} bytes`)
  for (const outPath of OUTPUTS) console.log(`- ${path.relative(REPO_ROOT, outPath)}`)
}

await main()

